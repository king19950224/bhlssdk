-- ============================================================================
-- JWT 即时失效：token_version（安全红线「停用 / 改角色 / 改密码后旧令牌立即失效」）
-- ----------------------------------------------------------------------------
-- 旧实现 access token 8h 有效且服务端无法吊销：停用 / 改角色 / 重置密码后，已签发的
-- JWT 仍可写操作（含下发设备命令）最长 8 小时（H2）。引入 token_version：
-- JWT 内嵌签发时的版本号，鉴权时与 users.token_version 比对，不一致即拒绝；
-- 停用 / 改角色 / 改密码 / 重置时自增该值，使该用户所有已签发令牌立即失效。
-- ============================================================================

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS token_version integer NOT NULL DEFAULT 0;

COMMENT ON COLUMN users.token_version IS 'JWT 版本号；自增即吊销该用户所有已签发令牌（停用/改角色/改密码时 +1）';
